const ALIASES: Record<string, string> = {
  'ci': 'ci/cd', 'cd': 'ci/cd', 'pr': 'pull request', 'k8s': 'kubernetes', 'tls': 'ssl', 'https': 'ssl', 'env': 'environment variable', 'env var': 'environment variable',
  'di': 'dependency injection', 'ts': 'typescript', 'vdom': 'virtual dom', 'token': 'llm token', 'conflict': 'merge conflict', 'lb': 'load balancer', 'o(n)': 'big o', 'hash': 'hashing',
}

let learned: Record<string, string> = {} // คำที่ Claude อธิบายให้แล้ว เก็บไว้ใช้ซ้ำ
let whispered = new Set<string>()
let whisper = true

function lookup(term: string): string | undefined {
  const k = term.toLowerCase().trim()
  return GLOSSARY[k] ? k : ALIASES[k] && GLOSSARY[ALIASES[k] ?? ''] ? ALIASES[k] : undefined
}

function card(key: string, e: Entry): string {
  return `${e.emoji} ${key.toUpperCase()}\n${e.short}\n💡 เหมือน: ${e.like}`
}

// ==========================================================================
// บทที่ 2: หาศัพท์ในข้อความที่พิมพ์ (เทียบทั้งคำ ไม่จับคำที่เป็นส่วนของคำอื่น)
// ==========================================================================
function termsIn(text: string): string[] {
  const lower = ` ${text.toLowerCase()} `
  const found = Object.keys(GLOSSARY).filter(k => new RegExp(`[^a-z0-9]${k.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}[^a-z0-9]`).test(lower))
  // ไม่กระซิบคำพื้นฐานเกินไป
  return found.filter(k => !['git', 'api', 'cache', 'docker', 'typescript', 'mock', 'async', 'session', 'cookie'].includes(k))
}

async function ask($: EngineInterface, term: string): Promise<string | undefined> {
  const system = 'อธิบายศัพท์ด้านซอฟต์แวร์ให้คนเพิ่งเริ่มเข้าใจ เป็นภาษาไทยที่เป็นธรรมชาติ 3 บรรทัด: บรรทัด 1 emoji หนึ่งตัวตามด้วยความหมายสั้นๆ ไม่เกิน 1 ประโยค, บรรทัด 2 ขึ้นต้นด้วย "💡 เหมือน:" แล้วเปรียบเทียบกับชีวิตประจำวัน, บรรทัด 3 ขึ้นต้นด้วย "🧪 ตัวอย่าง:" ตัวอย่างการใช้จริงสั้นๆ ถ้าไม่ใช่ศัพท์ด้านเทคนิคหรือไม่แน่ใจ ให้บอกตรงๆ'
  for (const model of ['haiku', await $.session.model()]) {
    const r = await $.model.complete({ model, system, prompt: term, maxTokens: 250 }).catch(() => undefined)
    if (r?.isAnswered) return r.text.trim()
  }
  return undefined
}

const HELP = `📚 Dev Dictionary TH (Mod 56)
========================================
/explain <ศัพท์>      อธิบายศัพท์ เช่น /explain cors
/explain list         คำทั้งหมดในคลัง (${Object.keys(GLOSSARY).length} คำ)
/explain random       สุ่มหนึ่งคำ
/explain whisper on|off  กระซิบความหมายเมื่อคุณพิมพ์ศัพท์ในคลัง (ตอนนี้: WHISPER)`

export const register: Register = on => {
  on('session.start', async ($, e, next) => {
    learned = ((await $.store.get('learned')) as Record<string, string> | undefined) ?? {}
    whisper = ((await $.store.get('whisper')) as boolean | undefined) ?? true
    whispered = new Set()
    await $.command.register({ name: 'explain', description: 'อธิบายศัพท์ Dev เป็นภาษาไทยแบบเข้าใจง่าย (/explain help)', argumentHint: '<ศัพท์>|list|random|whisper on|off' })
    return next(e)
  })

  // ==========================================================================
  // บทที่ 3: กระซิบ - พิมพ์ศัพท์ในคลัง เด้ง toast ความหมาย (ไม่แตะข้อความที่ส่ง)
  // ==========================================================================
  on('prompt.submit', async ($, e, next) => {
    if (whisper && !e.text.startsWith('/')) {
      const fresh = termsIn(e.text).filter(k => !whispered.has(k)).slice(0, 2)
      for (const k of fresh) {
        whispered.add(k)
        const g = GLOSSARY[k]
        if (g) $.ui.toast(`${g.emoji} ${k}: ${g.short}`, { timeoutMs: 12_000 })
      }
    }
    return next(e)
  })

  on('command.run', { command: 'explain' }, async ($, e) => {
    const term = e.args.trim()
    const [sub = '', value = ''] = term.split(/\s+/)
    if (!term || sub === 'help') return { text: HELP.replace('WHISPER', whisper ? 'เปิด' : 'ปิด') }
    if (sub === 'list') {
      const keys = Object.keys(GLOSSARY).sort()
      const extra = Object.keys(learned)
      return { text: `📚 คลังศัพท์ ${keys.length} คำ\n${keys.map(k => `${GLOSSARY[k]?.emoji} ${k}`).join('  ')}${extra.length ? `\n\n🧠 ที่ Claude อธิบายให้แล้ว: ${extra.join(', ')}` : ''}` }
    }
    if (sub === 'random') {
      const keys = Object.keys(GLOSSARY)
      const k = keys[Math.floor(((await $.clock.now()) / 1000) % keys.length)] ?? 'api'
      const g = GLOSSARY[k]
      return { text: g ? `🎲 ศัพท์สุ่ม\n\n${card(k, g)}` : '' }
    }
    if (sub === 'whisper' && (value === 'on' || value === 'off')) {
      whisper = value === 'on'
      await $.store.set('whisper', whisper)
      return { text: whisper ? '🤫 จะกระซิบความหมายเมื่อเจอศัพท์ในคลัง' : 'หยุดกระซิบแล้ว' }
    }
    const key = lookup(term)
    const g = key ? GLOSSARY[key] : undefined
    if (key && g) return { text: card(key, g) }
    const cached = learned[term.toLowerCase()]
    if (cached) return { text: `${term}\n${cached}` }
    // ==================================================================
    // บทที่ 4: ไม่มีในคลัง → ถาม Claude แล้วจำไว้ (คำละครั้ง ประหยัด token)
    // ==================================================================
    const answer = await ask($, term.slice(0, 80))
    if (!answer) return { text: '❌ ถาม Claude ไม่สำเร็จ' }
    learned = { ...learned, [term.toLowerCase()]: answer }
    const keys = Object.keys(learned)
    if (keys.length > 200) delete learned[keys[0] ?? '']
    await $.store.set('learned', learned)
    return { text: `${term}\n${answer}` }
  })
}

